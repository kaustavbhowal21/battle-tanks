import subprocess
import struct
import os
import shutil

def main():
    sw_dir = os.path.dirname(os.path.abspath(__file__))
    os.chdir(sw_dir)

    gcc = "riscv-none-elf-gcc"
    objdump = "riscv-none-elf-objdump"
    objcopy = "riscv-none-elf-objcopy"

    print("=== Compiling RV32IM C Game Software ===")
    cmd_compile = [
        gcc,
        "-march=rv32im",
        "-mabi=ilp32",
        "-O2",
        "-nostdlib",
        "-nostartfiles",
        "-ffreestanding",
        "-Iinclude",
        "-T", "linker.ld",
        "crt0.s",
        "src/main.c",
        "src/game.c",
        "src/physics.c",
        "-o", "game.elf"
    ]
    print("Running:", " ".join(cmd_compile))
    res = subprocess.run(cmd_compile, capture_output=True, text=True)
    if res.returncode != 0:
        print("Compilation FAILED:\n", res.stderr)
        return False
    print("Compilation SUCCESSFUL: game.elf created.")

    # Disassembly
    print("Generating disassembly game.dis...")
    with open("game.dis", "w", encoding="utf-8") as f:
        subprocess.run([objdump, "-d", "-M", "numeric", "game.elf"], stdout=f)

    # Extract ROM (instructions) and RAM (data)
    print("Extracting memory images...")
    subprocess.run([objcopy, "-O", "binary", "--only-section=.text*", "game.elf", "imem.bin"])
    subprocess.run([objcopy, "-O", "binary", "--only-section=.rodata*", "--only-section=.data*", "game.elf", "dmem.bin"])

    # Format 1024 words of 32-bit hex for Verilog $readmemh
    def bin_to_hex(bin_filename, hex_filename, num_words=1024, default_word=0):
        words = []
        if os.path.exists(bin_filename):
            with open(bin_filename, "rb") as f:
                data = f.read()
            for i in range(0, len(data), 4):
                chunk = data[i:i+4]
                if len(chunk) < 4:
                    chunk = chunk.ljust(4, b'\x00')
                val = struct.unpack("<I", chunk)[0]
                words.append(val)
        
        while len(words) < num_words:
            words.append(default_word)

        words = words[:num_words]

        with open(hex_filename, "w", encoding="utf-8") as f:
            for w in words:
                f.write(f"{w:08x}\n")
        print(f"Generated {hex_filename} ({len(words)} words)")

    # Default for IMEM is NOP (0x00000013), for DMEM is 0
    bin_to_hex("imem.bin", "imem.hex", num_words=1024, default_word=0x00000013)
    bin_to_hex("dmem.bin", "dmem.hex", num_words=1024, default_word=0x00000000)

    # Copy hex files to modules/ and root directory
    targets = [
        os.path.join(sw_dir, "..", "imem.hex"),
        os.path.join(sw_dir, "..", "dmem.hex"),
        os.path.join(sw_dir, "..", "modules", "imem.hex"),
        os.path.join(sw_dir, "..", "modules", "dmem.hex"),
        os.path.join(sw_dir, "..", "modules", "cpu", "imem.hex"),
        os.path.join(sw_dir, "..", "modules", "cpu", "dmem.hex"),
        os.path.join(sw_dir, "..", "modules", "sim", "imem.hex"),
        os.path.join(sw_dir, "..", "modules", "sim", "dmem.hex")
    ]
    # Embedded firmware images for synthesis (included by modules/cpu/memory.v).
    # These make the bitstream independent of Vivado locating imem.hex/dmem.hex.
    def hex_to_vh(hex_filename, vh_filename, array_name):
        with open(hex_filename, "r", encoding="utf-8") as f:
            words = [ln.strip() for ln in f if ln.strip()]
        with open(vh_filename, "w", encoding="utf-8", newline="\n") as f:
            f.write("// AUTO-GENERATED by software/build_and_export.py -- DO NOT EDIT.\n")
            f.write(f"// Embedded {array_name} image ({len(words)} words) used when HEX_FILE == \"\".\n")
            for i, w in enumerate(words):
                f.write(f"                {array_name}[{i}] = 32'h{w};\n")
        print(f"Generated {vh_filename}")

    cpu_dir = os.path.join(sw_dir, "..", "modules", "cpu")
    hex_to_vh("imem.hex", os.path.join(cpu_dir, "firmware_imem.vh"), "imem")
    hex_to_vh("dmem.hex", os.path.join(cpu_dir, "firmware_dmem.vh"), "dmem")

    for t in targets:
        os.makedirs(os.path.dirname(t), exist_ok=True)
        if "imem" in t:
            shutil.copyfile("imem.hex", t)
        else:
            shutil.copyfile("dmem.hex", t)

    print("=== Software build and export complete! ===")
    return True

if __name__ == "__main__":
    main()
